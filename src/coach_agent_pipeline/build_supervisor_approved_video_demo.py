"""Build a client-ready video demo using the supervisor-approved coach agent."""

from __future__ import annotations

import os
import textwrap
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import cv2
import pandas as pd

from coach_agent_runtime import SimulatedCoachAgent


PHASE_ROOT = Path(__file__).resolve().parent
INPUT_VIDEO = Path(
    os.getenv(
        "COACH_AGENT_INPUT_VIDEO",
        str(PHASE_ROOT / "data" / "input_video.mp4"),
    )
)
RARE_DATA = PHASE_ROOT / "data" / "coach_reaction_dataset_rare_only.csv"
OUTPUT_DIR = PHASE_ROOT / "outputs" / "video_demo"
OUTPUT_VIDEO = OUTPUT_DIR / "supervisor_approved_agent_side_panel_demo.mp4"
OUTPUT_STREAM = PHASE_ROOT / "data" / "supervisor_approved_video_decision_stream.csv"


@dataclass(frozen=True)
class VideoSpec:
    """Video rendering dimensions."""

    match_width: int
    panel_width: int
    height: int
    fps: float

    @property
    def output_width(self) -> int:
        """Total output width."""
        return self.match_width + self.panel_width


def main() -> None:
    """Create final video demo and its decision stream."""
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    decision_stream = build_decision_stream(INPUT_VIDEO)
    decision_stream.to_csv(OUTPUT_STREAM, index=False, encoding="utf-8")
    render_video(INPUT_VIDEO, decision_stream, OUTPUT_VIDEO)
    print("Supervisor-approved video demo created")
    print(f"Video: {OUTPUT_VIDEO}")
    print(f"Decision stream: {OUTPUT_STREAM}")


def build_decision_stream(video_path: Path) -> pd.DataFrame:
    """Build timed supervisor-approved decisions for the video."""
    duration = get_video_duration(video_path)
    windows = build_video_windows(duration, window_seconds=5.0)
    rare_rows = select_diverse_rare_event_rows(len(windows))
    agent = SimulatedCoachAgent()
    recommendations = agent.recommend_many(rare_rows)

    stream = pd.DataFrame(windows)
    stream = pd.concat([stream.reset_index(drop=True), recommendations.reset_index(drop=True)], axis=1)
    stream["display_decision"] = stream["selected_policy_action"]
    stream["high_risk_window"] = stream["urgency"].isin(["high", "critical"])
    stream["demo_note"] = (
        "Video timing comes from the Phase 3 demo clip; coach decisions are generated by the "
        "supervisor-approved coach-agent bundle from rare-event match-window states."
    )
    return stream


def get_video_duration(video_path: Path) -> float:
    """Return video duration in seconds."""
    capture = cv2.VideoCapture(str(video_path))
    if not capture.isOpened():
        raise FileNotFoundError(f"Could not open video: {video_path}")
    frame_count = capture.get(cv2.CAP_PROP_FRAME_COUNT)
    fps = capture.get(cv2.CAP_PROP_FPS) or 30.0
    capture.release()
    return float(frame_count / fps)


def build_video_windows(duration: float, window_seconds: float) -> list[dict[str, float | int]]:
    """Build fixed windows across a video duration."""
    rows = []
    start = 0.0
    window_id = 1
    while start < duration:
        end = min(duration, start + window_seconds)
        if end - start < 2.5:
            if rows:
                rows[-1]["end_time_seconds"] = round(end, 2)
            break
        rows.append({"window_id": window_id, "start_time_seconds": round(start, 2), "end_time_seconds": round(end, 2)})
        start += window_seconds
        window_id += 1
    return rows


def select_diverse_rare_event_rows(required_rows: int) -> pd.DataFrame:
    """Select a diverse set of rare-event rows for the demo."""
    data = pd.read_csv(RARE_DATA)
    preferred_reasons = [
        ("Red Card", "max"),
        ("Second Yellow", "max"),
        ("Unexpected Goal", "median"),
        ("Penalty Goal", "median"),
        ("Formation Change", "median"),
        ("Substitutions (2)", "median"),
        ("Error Cluster", "low"),
        ("Formation Change, Error Cluster", "median"),
        ("Unexpected Goal, Error Cluster", "low"),
    ]
    selected = []
    for reason, strategy in preferred_reasons:
        matches = data[data["rare_event_reason"] == reason]
        if not matches.empty:
            selected.append(select_row_by_strategy(matches, strategy))
    selected_frame = pd.DataFrame(selected)
    if len(selected_frame) < required_rows:
        remainder = data.sort_values("tactical_shift_score", ascending=False).head(required_rows - len(selected_frame))
        selected_frame = pd.concat([selected_frame, remainder], ignore_index=True)
    selected_frame = selected_frame.head(required_rows).copy()
    for column in selected_frame.columns:
        if column.startswith("is_") or column.startswith("has_"):
            selected_frame[column] = selected_frame[column].astype(str)
    return selected_frame


def select_row_by_strategy(rows: pd.DataFrame, strategy: str) -> pd.Series:
    """Select one row from a rare-event group."""
    sorted_rows = rows.sort_values("tactical_shift_score", ascending=True).reset_index(drop=True)
    if strategy == "max":
        return sorted_rows.iloc[-1]
    if strategy == "low":
        index = max(0, int(len(sorted_rows) * 0.20))
        return sorted_rows.iloc[index]
    index = max(0, int(len(sorted_rows) * 0.50))
    return sorted_rows.iloc[index]


def render_video(input_video: Path, stream: pd.DataFrame, output_video: Path) -> None:
    """Render the final side-panel video."""
    capture = cv2.VideoCapture(str(input_video))
    if not capture.isOpened():
        raise FileNotFoundError(f"Could not open video: {input_video}")
    fps = capture.get(cv2.CAP_PROP_FPS) or 30.0
    source_width = int(capture.get(cv2.CAP_PROP_FRAME_WIDTH))
    source_height = int(capture.get(cv2.CAP_PROP_FRAME_HEIGHT))
    spec = VideoSpec(match_width=min(1024, source_width), panel_width=460, height=source_height, fps=fps)
    writer = cv2.VideoWriter(
        str(output_video),
        cv2.VideoWriter_fourcc(*"mp4v"),
        spec.fps,
        (spec.output_width, spec.height),
    )
    frame_index = 0
    while True:
        ok, frame = capture.read()
        if not ok:
            break
        timestamp = frame_index / spec.fps
        current = current_decision(stream, timestamp)
        canvas = build_canvas(frame, spec, current, stream, timestamp)
        writer.write(canvas)
        frame_index += 1
    capture.release()
    writer.release()


def current_decision(stream: pd.DataFrame, timestamp: float) -> dict[str, Any]:
    """Find current decision for a video timestamp."""
    matches = stream[
        (stream["start_time_seconds"] <= timestamp)
        & (stream["end_time_seconds"] > timestamp)
    ]
    if matches.empty:
        return stream.iloc[-1].to_dict()
    return matches.iloc[0].to_dict()


def build_canvas(
    frame,
    spec: VideoSpec,
    decision: dict[str, Any],
    stream: pd.DataFrame,
    timestamp: float,
):
    """Build one output frame with match crop and side panel."""
    match_frame = frame[:, : spec.match_width]
    if match_frame.shape[1] != spec.match_width or match_frame.shape[0] != spec.height:
        match_frame = cv2.resize(match_frame, (spec.match_width, spec.height))
    panel = build_panel(spec, decision, stream, timestamp)
    canvas = cv2.hconcat([match_frame, panel])
    draw_match_overlay(canvas, decision, timestamp)
    return canvas


def build_panel(spec: VideoSpec, decision: dict[str, Any], stream: pd.DataFrame, timestamp: float):
    """Render side panel."""
    panel = new_panel(spec.panel_width, spec.height, color=(18, 24, 33))
    x = 24
    y = 38
    draw_text(panel, "SUPERVISOR-APPROVED", x, y, size=0.62, color=(113, 211, 255), weight=2)
    draw_text(panel, "COACH AGENT", x, y + 34, size=0.92, color=(255, 255, 255), weight=2)
    draw_text(panel, f"Time {timestamp:05.1f}s | Window {int(decision['window_id'])}", x, y + 72, size=0.48, color=(190, 199, 213), weight=1)

    y += 118
    urgency = str(decision["urgency"]).upper()
    urgency_color = urgency_to_color(str(decision["urgency"]))
    draw_badge(panel, x, y, f"URGENCY: {urgency}", urgency_color)
    draw_badge(panel, x + 190, y, f"CONF {float(decision['policy_confidence']):.2f}", (51, 92, 158))

    y += 58
    draw_label_value(panel, "Rare Event", str(decision["rare_event_reason"]), x, y)
    y += 64
    draw_wrapped_section(panel, "Decision", str(decision["display_decision"]), x, y, width_chars=38)
    y += 126
    draw_wrapped_section(panel, "Reason", str(decision["explanation"]), x, y, width_chars=42, line_size=0.42)
    y += 132
    if bool(decision["high_risk_window"]):
        draw_badge(panel, x, y, "HIGH RISK WINDOW", (30, 64, 175))
    else:
        draw_badge(panel, x, y, "MONITOR WINDOW", (50, 94, 72))

    y += 58
    draw_text(panel, "Source", x, y, size=0.45, color=(156, 163, 175), weight=1)
    draw_text(panel, str(decision["source"]), x, y + 24, size=0.43, color=(226, 232, 240), weight=1)
    draw_timeline(panel, stream, timestamp, spec.height - 56)
    return panel


def new_panel(width: int, height: int, color: tuple[int, int, int]):
    """Create solid-color panel image."""
    import numpy as np

    panel = np.zeros((height, width, 3), dtype=np.uint8)
    panel[:, :] = color
    return panel


def draw_match_overlay(canvas, decision: dict[str, Any], timestamp: float) -> None:
    """Draw compact overlay on the match area."""
    cv2.rectangle(canvas, (18, 18), (620, 86), (15, 23, 42), -1)
    cv2.rectangle(canvas, (18, 18), (620, 86), (71, 85, 105), 1)
    draw_text(canvas, "Team A vs Team B | Tactical Decision Assistant", 34, 44, size=0.58, color=(255, 255, 255), weight=2)
    draw_text(canvas, f"{timestamp:05.1f}s  |  {decision['rare_event_reason']}  |  {str(decision['urgency']).upper()}", 34, 70, size=0.48, color=(203, 213, 225), weight=1)


def draw_badge(image, x: int, y: int, text: str, color: tuple[int, int, int]) -> None:
    """Draw a badge."""
    width = max(120, 13 * len(text))
    cv2.rectangle(image, (x, y), (x + width, y + 34), color, -1)
    cv2.rectangle(image, (x, y), (x + width, y + 34), (214, 226, 240), 1)
    draw_text(image, text, x + 12, y + 23, size=0.45, color=(255, 255, 255), weight=2)


def draw_label_value(image, label: str, value: str, x: int, y: int) -> None:
    """Draw label/value text."""
    draw_text(image, label, x, y, size=0.44, color=(156, 163, 175), weight=1)
    draw_text(image, value[:48], x, y + 28, size=0.58, color=(255, 255, 255), weight=2)


def draw_wrapped_section(
    image,
    label: str,
    value: str,
    x: int,
    y: int,
    width_chars: int,
    line_size: float = 0.46,
) -> None:
    """Draw a wrapped text section."""
    draw_text(image, label, x, y, size=0.44, color=(156, 163, 175), weight=1)
    for index, line in enumerate(textwrap.wrap(value, width=width_chars)[:5]):
        draw_text(image, line, x, y + 28 + index * 22, size=line_size, color=(241, 245, 249), weight=1)


def draw_timeline(panel, stream: pd.DataFrame, timestamp: float, y: int) -> None:
    """Draw a simple video timeline with urgency colors."""
    x0 = 24
    width = panel.shape[1] - 48
    total = float(stream["end_time_seconds"].max())
    cv2.line(panel, (x0, y), (x0 + width, y), (100, 116, 139), 3)
    for _, row in stream.iterrows():
        sx = x0 + int(width * float(row["start_time_seconds"]) / total)
        ex = x0 + int(width * float(row["end_time_seconds"]) / total)
        cv2.line(panel, (sx, y), (ex, y), urgency_to_color(str(row["urgency"])), 7)
    cx = x0 + int(width * timestamp / total)
    cv2.circle(panel, (cx, y), 7, (255, 255, 255), -1)
    draw_text(panel, "Decision timeline", x0, y - 18, size=0.4, color=(156, 163, 175), weight=1)


def draw_text(
    image,
    text: str,
    x: int,
    y: int,
    size: float,
    color: tuple[int, int, int],
    weight: int,
) -> None:
    """Draw text using OpenCV."""
    cv2.putText(image, text, (x, y), cv2.FONT_HERSHEY_SIMPLEX, size, color, weight, cv2.LINE_AA)


def urgency_to_color(urgency: str) -> tuple[int, int, int]:
    """Map urgency to BGR color."""
    colors = {
        "critical": (43, 61, 220),
        "high": (25, 139, 245),
        "medium": (48, 160, 96),
        "low": (148, 163, 184),
    }
    return colors.get(urgency.lower(), (148, 163, 184))


